'use strict';
const assert=require('node:assert/strict');
const A=require('../web/dnd-action.js'),V=require('../web/vault-store.js');
const hero=()=>({schema_version:1,name:'Target QA',system_edition:'dnd-2014',hp:{current:30,max:30,temp:0},ac:16,inventory:[],effects:{},conditions:[],attacks:[{id:'sword',name:'Sword',damage:'1d8+4 slashing',bonus:6}],spells:[],actions:[],resources:{}});
const h=hero(),before=JSON.stringify(h);
assert.throws(()=>A.requireOffensiveTarget(h,'self'),/Choose an encounter creature/);
assert.throws(()=>A.requireOffensiveTarget(h,null),/Choose an encounter creature/);
assert.equal(JSON.stringify(h),before,'Rejected self/empty attack targets must not mutate the character');
const goblin=A.addTarget(h,{name:'Goblin',ac:15,hp:18});
assert.equal(A.requireOffensiveTarget(h,goblin.id),goblin);
assert.throws(()=>A.requireOffensiveTarget(h,'target-invalid'),/no longer available/);
assert.throws(()=>A.setTargetAutoDamage(h,'self',true),/Choose an encounter creature/);
assert.throws(()=>A.setTargetAutoDamage(h,goblin.id,'yes'),/explicitly/);
assert.equal(A.canAutoApplyAttackDamage(h,goblin.id,'slashing','weapon'),false,'No automatic HP changes without encounter and approval');
A.setEncounter(h,true);A.setCombatMode(h,'auto');
assert.equal(A.canAutoEvaluateAttack(h,goblin.id),true);
assert.equal(A.canAutoApplyAttackDamage(h,goblin.id,'slashing','weapon'),false,'Target defenses not yet reviewed');
A.setTargetAutoDamage(h,goblin.id,true);
assert.equal(A.canAutoApplyAttackDamage(h,goblin.id,'slashing','weapon'),true);
assert.equal(A.canAutoApplyAttackDamage(h,goblin.id,'slashing','unspecified'),false,'Unclassified imported attacks cannot auto-apply');
assert.equal(A.canAutoApplyAttackDamage(h,goblin.id,'untyped','weapon'),false,'Unknown damage type requires review');
assert.equal(A.canAutoApplyAttackDamage(h,'self','slashing','weapon'),false,'Self never auto-damaged by attack');
const plan=A.planDamage(h,goblin.id,{amount:8,type:'slashing'});
assert.equal(goblin.hp.current,18,'Planning must be pure');
const result=A.commitDamage(h,plan);
assert.equal(result.hpLoss,8);assert.equal(goblin.hp.current,10);
assert.equal(A.undoLastDamage(h),true);assert.equal(goblin.hp.current,18,'Auto-eligible damage uses existing undo');
A.setTargetTraits(h,goblin.id,'resistances','slashing');
assert.equal(A.canAutoApplyAttackDamage(h,goblin.id,'slashing','weapon'),false,'Changing defensive traits revokes approval');
assert.equal(goblin.auto_damage,false);
A.setTargetAutoDamage(h,goblin.id,true);
A.setTargetTraits(h,goblin.id,'resistances','slashing');
assert.equal(A.canAutoApplyAttackDamage(h,goblin.id,'slashing','weapon'),true,'Idempotent traits update keeps approval');
A.setTargetCondition(h,goblin.id,'Invisible',true);
assert.equal(A.canAutoEvaluateAttack(h,goblin.id),false,'Unqualified defender conditions require DM review');
A.setTargetCondition(h,goblin.id,'Invisible',false);
assert.equal(A.canAutoEvaluateAttack(h,goblin.id),true);
h.conditions.push('Blinded');
assert.equal(A.canAutoEvaluateAttack(h,goblin.id),false,'Unqualified attacker conditions require DM review');
h.conditions.length=0;
A.setCombatMode(h,'guided');
assert.equal(A.canAutoEvaluateAttack(h,goblin.id),false);
assert.equal(A.canAutoApplyAttackDamage(h,goblin.id,'slashing','weapon'),false,'Guided never auto-applies');
A.setCombatMode(h,'manual');
assert.equal(A.canAutoApplyAttackDamage(h,goblin.id,'slashing','weapon'),false,'Manual never auto-applies');
A.setCombatMode(h,'auto');
const saved=V.reconcile(h,hero());
assert.equal(A.targetById(saved,goblin.id).auto_damage,true,'Reviewed target stays in original character vault reimport state');
A.removeTarget(h,goblin.id);
assert.throws(()=>A.requireOffensiveTarget(h,goblin.id),/no longer available/);
assert.equal(A.canAutoApplyAttackDamage(h,goblin.id,'slashing','weapon'),false,'Removed target cannot be auto-damaged');
console.log('PASS target safety: explicit opponent, review approval, typed damage, profile invalidation, conditions, modes, undo, reimport and removal');

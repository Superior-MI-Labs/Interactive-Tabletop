'use strict';
const assert=require('node:assert/strict');
const A=require('../web/dnd-action.js'),V=require('../web/vault-store.js');
const character=()=>({schema_version:1,name:'Event QA',system_edition:'dnd-2014',effects:{},resources:{Ki:{current:2,max:2},'Warding Flare Uses':{current:2,max:2}},conditions:[],inventory:[],actions:[],hp:{current:20,max:20}});
const deflect={id:'deflect',name:'Deflect',activation:'1 reaction',roll:'1d10+5',cost:0,workflow:{kind:'damage-reduction',followup:{label:'Return',resource:'Ki',cost:1,roll:'1d20+5',requires_catchable:true,requires_free_hand:true}}};
const flare={id:'flare',activation:'1 reaction',trigger_event:'incoming-attack',resource:'Warding Flare Uses',cost:1};
const stun={id:'stun',activation:'special',trigger_event:'melee-hit',resource:'Ki',cost:1};
let c=character();A.setEncounter(c,true);
assert.throws(()=>A.beginWorkflow(c,A.plan(c,deflect),8),/ranged-hit/);
assert.equal(A.combat(c).economy.spent.reaction,0);
A.recordCombatEvent(c,'incoming-attack');
assert.throws(()=>A.beginWorkflow(c,A.plan(c,deflect),8),/ranged-hit/);
assert.throws(()=>A.commitUsage(c,A.plan(c,stun)),/melee-hit/);
A.commitUsage(c,A.plan(c,flare));
assert.equal(c.resources['Warding Flare Uses'].current,1);
assert.equal(A.combatEvent(c).used,true);
assert.throws(()=>A.commitUsage(c,A.plan(c,flare)),/incoming-attack|already used/);
const snap=JSON.stringify(c);
assert.throws(()=>A.commitUsage(c,A.plan(c,stun)),/melee-hit/);
assert.equal(JSON.stringify(c),snap,'Invalid event must not spend or mutate resources');
A.advanceTurn(c);assert.equal(A.combatEvent(c),null);
A.recordCombatEvent(c,'ranged-hit');const flow=A.beginWorkflow(c,A.plan(c,deflect),9);
assert.equal(A.combatEvent(c).used,true);
assert.throws(()=>A.beginWorkflow(c,A.plan(c,deflect),3),/existing staged/);
A.resolveWorkflow(c,flow.id,1);assert.equal(c.resources.Ki.current,2);
A.advanceTurn(c);A.recordCombatEvent(c,'melee-hit');A.commitUsage(c,A.plan(c,stun));
assert.equal(c.resources.Ki.current,1);assert.equal(A.combat(c).economy.spent.reaction,0,'Stun follow-up is not another reaction');
assert.throws(()=>A.commitUsage(c,A.plan(c,stun)),/melee-hit/);
A.recordCombatEvent(c,'melee-hit');A.commitUsage(c,A.plan(c,stun));assert.equal(c.resources.Ki.current,0);
const saved=V.normalize({schema_version:1,active_id:'a',characters:[{id:'a',character:c}]});
assert.equal(A.combatEvent(saved.characters[0].character).used,true);
A.setCombatMode(c,'manual');A.dismissCombatEvent(c);assert.equal(A.combatEvent(c),null);
const beforeReaction=A.combat(c).economy.spent.reaction;
A.commitUsage(c,A.plan(c,{...flare,cost:0}));assert.equal(A.combat(c).economy.spent.reaction,beforeReaction);
assert.throws(()=>A.recordCombatEvent(c,'__proto__'),/Unknown combat event/);
assert.throws(()=>A.plan(c,{id:'broken',trigger_event:'script',activation:'1 reaction'}),/Unsupported ability trigger/);
A.setEncounter(c,false);assert.throws(()=>A.recordCombatEvent(c,'incoming-attack'),/Start encounter/);
console.log('Event windows: phases, reaction timing, one-use identity, edition rules, safe costs and vault PASS');

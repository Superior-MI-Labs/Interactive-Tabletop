'use strict';
const assert=require('node:assert/strict');
const A=require('../web/dnd-action.js');
assert.deepEqual(A.resolveD20([11],5,'normal'),{natural:11,total:16,parts:[11],modifier:5,mode:'normal'});
assert.equal(A.resolveD20([2,19],7,'advantage').total,26);
assert.equal(A.resolveD20([2,19],7,'disadvantage').total,9);
assert.equal(A.resolveD20([20,1],2,'disadvantage').natural,1);
assert.equal(A.evaluateAttack(26,20,A.resolveD20([20,3],6,'advantage').natural).critical,true);
assert.equal(A.evaluateAttack(9,20,A.resolveD20([19,1],8,'disadvantage').natural).automaticMiss,true);
assert.throws(()=>A.resolveD20([8],2,'advantage'),/2 valid/);
assert.throws(()=>A.resolveD20([21],2,'normal'),/valid/);
assert.equal(A.criticalDamageExpression('1d8+4'),'2d8+4');
assert.equal(A.criticalDamageExpression('2d6-1'),'4d6-1');
assert.equal(A.criticalDamageExpression('1d10'),'2d10');
assert.throws(()=>A.criticalDamageExpression('12d6+4'),/up to 10/);
const c={ac:14,hp:{max:10,current:10,temp:0},effects:{},conditions:[]};
const t=A.addTarget(c,{name:'Wolf',ac:12,hp:10});
assert.deepEqual(A.setTargetCondition(c,t.id,'Prone',true),['Prone']);
assert.deepEqual(A.setTargetCondition(c,t.id,'Prone',true),['Prone']);
assert.deepEqual(A.setTargetCondition(c,t.id,'Prone',false),[]);
assert.equal(t.hp.current,10,'Manual conditions never change HP');
assert.throws(()=>A.setTargetCondition(c,t.id,'Homebrew Sleep',true),/Unknown D&D condition/);
console.log('d20 modes, critical damage, explicit target conditions PASS');

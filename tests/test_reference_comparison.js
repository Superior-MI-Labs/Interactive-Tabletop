const assert=require('node:assert/strict');
const fs=require('node:fs');
const Ref=require('../web/reference-catalog.js');
Ref.init(JSON.parse(fs.readFileSync(require('node:path').join(__dirname,'../web/dnd-2014-reference.json'),'utf8')));
const spell=Ref.match('spell','Bless');
const original={name:'Bless',level:1,casting_time:'1 Action',range:'30 ft.',components:'V, S, M (holy water)',duration:'Concentration, up to 1 minute',prepared:true};
const before=JSON.stringify(original);
const rows=Ref.compareSpell(original,spell);
assert.equal(rows.length,5);
assert.ok(rows.every(x=>x.status==='match'),JSON.stringify(rows));
assert.equal(JSON.stringify(original),before,'comparing must be pure');
const changed=Ref.compareSpell({...original,level:2,range:'99 feet',components:''},spell);
assert.equal(changed[0].status,'review');
assert.equal(changed[2].status,'review');
assert.equal(changed[3].status,'not-recorded');
assert.equal(Ref.actionDraft(spell).cost,0);
assert.equal(Ref.actionDraft(spell).roll,'');
assert.equal(Ref.actionDraft(spell).effect_kind,'none');
assert.equal(Ref.actionDraft(spell).source,'manual');
assert.equal(Ref.actionDraft(spell).activation,'action');
assert.equal(Ref.actionDraft(Ref.match('spell','Healing Word')).activation,'bonus action');
assert.equal(Ref.actionDraft(Ref.match('spell','Counterspell')).activation,'reaction');
assert.throws(()=>Ref.actionDraft({name:'custom',kind:'equipment'}));
console.log('SRD comparison + inert custom action draft tests PASS');

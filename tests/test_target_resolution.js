'use strict';
const assert=require('node:assert/strict');
const A=require('../web/dnd-action.js');
const V=require('../web/vault-store.js');
const sample=()=>({schema_version:1,name:'Test Hero',ac:17,inventory:[],hp:{current:32,max:40,temp:6},conditions:[],resources:{},effects:{},spells:[],actions:[]});
const c=sample(),g=A.addTarget(c,{name:'Stone Guardian',ac:18,hp:51});
assert.deepEqual(A.targets(c).map(t=>t.id),[g.id]);
assert.deepEqual(g.hp,{max:51,current:51,temp:0});
assert.equal(g.saves.CON,0);
assert.throws(()=>A.addTarget(c,{name:'Stone Guardian',ac:8,hp:10}),/already exists/);
assert.throws(()=>A.addTarget(c,{name:'X',ac:'not number',hp:10}),/AC must/);
assert.throws(()=>A.updateTargetStat(c,g.id,'hack',5),/Unsupported/);
A.updateTargetStat(c,g.id,'saves.CON',8);
assert.equal(g.saves.CON,8);
assert.equal(A.evaluateSave(17,18).success,false);
assert.equal(A.evaluateSave(18,18).success,true);
assert.equal(A.evaluateSave(1,15).success,false,'2014 saving throws do not automatically pass on natural 1');
assert.equal(A.evaluateAttack(1,18,20).critical,true);
assert.equal(A.evaluateAttack(50,18,1).automaticMiss,true);
assert.equal(A.evaluateAttack(18,18).hit,true);
assert.equal(A.evaluateAttack(17,18).hit,false);
assert.throws(()=>A.damageTraits('fire,laser'),/Unknown damage type/);
A.setTargetTraits(c,g.id,'resistances','fire, cold, fire');
A.setTargetTraits(c,g.id,'vulnerabilities','fire');
A.setTargetTraits(c,g.id,'immunities','poison');
const half=A.planDamage(c,g.id,{amount:25,type:'fire',saveOutcome:'success',savePolicy:'half'});
assert.equal(half.amount,12,'25 half-on-save => 12; resistance => 6; vulnerability => 12');
assert.equal(g.hp.current,51,'planning is pure');
assert.equal(A.commitDamage(c,half).hpLoss,12);assert.equal(g.hp.current,39);
assert.equal(A.undoLastDamage(c),true);assert.equal(g.hp.current,51);
assert.equal(A.undoLastDamage(c),false);
const immunity=A.planDamage(c,g.id,{amount:999,type:'poison'});assert.equal(immunity.amount,0);
assert.equal(A.commitDamage(c,immunity).hpLoss,0);assert.equal(g.hp.current,51);
A.updateTargetStat(c,g.id,'hp.temp',7);
const resisted=A.planDamage(c,g.id,{amount:25,type:'cold'});
assert.equal(resisted.amount,12);assert.equal(resisted.absorbed,7);assert.equal(resisted.hpLoss,5);
A.updateTargetStat(c,g.id,'hp.current',40);
assert.throws(()=>A.commitDamage(c,resisted),/changed/,'Stale preview cannot be applied');
const hit=A.planDamage(c,g.id,{amount:25,type:'cold'});A.commitDamage(c,hit);
assert.equal(g.hp.current,35);assert.equal(g.hp.temp,0);
g.hp.current=22;assert.throws(()=>A.undoLastDamage(c),/Undo is no longer safe/);
assert.throws(()=>A.planDamage(c,g.id,{amount:2,type:'fire',saveOutcome:'success'}),/both a saving throw/);
assert.throws(()=>A.planDamage(c,g.id,{amount:-4,type:'fire'}),/integer/);
assert.throws(()=>A.planDamage(c,'deleted',{amount:4}),/Choose a valid target/);
// Combat state: each character owns its target roster; PDF reimports retain effects.
const updated=sample();const merged=V.reconcile(c,updated);
assert.equal(merged.effects.targets[0].hp.current,22);
assert.equal(updated.effects.targets,undefined);
assert.equal(merged.ac,17);
const hero=sample();hero.effects.self_traits={resistances:['fire']};
hero.effects.active=[{id:'spell:faith1',name:'Shield of Faith',target:'self',ac_bonus:2,modifiers:[{stat:'ac',amount:2}],stack_key:'spell:shieldoffaith'},
 {id:'spell:faith2',name:'Shield of Faith',target:'self',modifiers:[{stat:'ac',amount:2}],stack_key:'spell:shieldoffaith'},
 {id:'spell:other',name:'Blessed Shield',target:'self',modifiers:[{stat:'ac',amount:1}],stack_key:'spell:blessedshield'}];
assert.equal(A.effectiveAC(hero),20,'Same named spell does not double stack, distinct adds');
assert.equal(hero.ac,17,'Imported AC remains unchanged');
hero.effects.active=[];
const checkEffect={kind:'spell',sourceId:'s',name:'Aura',durationRounds:10,concentration:true};
A.startEffect(hero,checkEffect);
assert.equal(A.activeEffects(hero).length,1);
const damage=A.planDamage(hero,'self',{amount:25,type:'fire'});
assert.equal(damage.amount,12);assert.equal(damage.absorbed,6);
const applied=A.commitDamage(hero,damage);
assert.equal(hero.hp.current,26);
assert.equal(applied.concentrationCheck.dc,10,'Concentration DC based on damage after resistance, not HP damage');
assert.equal(hero.effects.pending_concentration.length,1);
assert.equal(A.undoLastDamage(hero),true);assert.equal(hero.hp.current,32);assert.equal(hero.hp.temp,6);
assert.equal(hero.effects.pending_concentration.length,0);
assert.equal(A.removeTarget(c,g.id),true);assert.equal(A.targets(c).length,0);
assert.equal(A.removeTarget(c,g.id),false);
// Explicitly configured, edition-neutral damage rolls; no automatic targeting from spell prose.
const spell={id:'sp1',name:'Homebrew Blast',level:1,source:'DM',prepared:true,roll:'2d6+3',effect_kind:'damage',damage_type:'lightning'};
hero.resources['Level 1 Spell Slots']={current:2,max:2};
const plan=A.planSpell(hero,spell,1);assert.equal(plan.effect,'damage');assert.equal(plan.damageType,'lightning');
assert.equal(plan.roll.expression,'2d6+3');
const revised=sample();revised.spells=[{...spell,roll:'',effect_kind:'none'}];const oldSpellChar=sample();oldSpellChar.spells=[spell];
assert.equal(V.reconcile(oldSpellChar,revised).spells[0].damage_type,'lightning','Manual spell damage type survives PDF reimport');
A.commitUsage(hero,plan);assert.equal(hero.resources['Level 1 Spell Slots'].current,1);
assert.throws(()=>A.planSpell(hero,{...spell,damage_type:'superfire'},1),/Invalid spell damage/);
const ability={id:'a',name:'Flame Palm',activation:'action',roll:'1d8',effect_kind:'damage',damage_type:'fire',cost:0};
assert.equal(A.plan(hero,ability).damageType,'fire');
assert.throws(()=>A.plan(hero,{...ability,roll:''}),/Damage requires/);

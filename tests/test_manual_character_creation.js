const assert=require('node:assert/strict');
const Import=require('../web/character-import.js');
const Vault=require('../web/vault-store.js');
const Demo=require('../web/demo-character.js');
const score=Object.fromEntries(['STR','DEX','CON','INT','WIS','CHA'].map((k,i)=>[k,[16,14,13,12,10,8][i]]));
const details={name:'Kael Sparrow',className:'Ranger',level:5,species:'Elf',background:'Outlander',
 scores:score,saveProficiencies:['STR','DEX'],skillProficiencies:['Athletics','Perception'],
 ac:15,hp:37,speed:35,attack:{name:'Longbow',bonus:7,damage:'1d8+4',range:'ranged'}};
const created=Import.createManual(details);
assert(Vault.validCharacter(created));
assert.equal(created.import_provenance,'Manual character creation (local)');
assert.equal(created.system_edition,'dnd-2014');
assert.equal(created.rules_profile,'manual','No automatic rules granted by name');
assert.equal(created.class_level,'Ranger 5');
assert.equal(created.proficiency,3);
assert.equal(created.initiative,2);
assert.equal(created.abilities.STR.modifier,3);
assert.equal(created.abilities.CHA.modifier,-1);
assert.equal(created.saves.Strength,6);
assert.equal(created.saves.Dexterity,5);
assert.equal(created.saves.Constitution,1);
assert.equal(created.skills.Athletics,6);
assert.equal(created.skills.Perception,3);
assert.equal(created.skills.Arcana,1);
assert.deepEqual(created.attacks,[{name:'Longbow',bonus:7,damage:'1d8+4',type:'attack',attack_type:'weapon',attack_range:'ranged'}]);
assert.deepEqual(created.actions,[]);
assert.deepEqual(created.spells,[]);
assert.deepEqual(created.resources,{});
assert.equal(created.hp.current,37);
assert.equal(created.demo_id,undefined,'Manual sheet is not the demo');
const vault=Vault.empty();Vault.addDemo(vault);const demoId=vault.active_id;
Vault.upsert(vault,'manual-created',created);const normalized=Vault.normalize(vault);
assert.equal(normalized.characters.length,2,'Creation must not overwrite demo');
assert.equal(normalized.active_id,'manual-created');
assert.equal(normalized.characters.find(x=>x.id===demoId).character.demo_id,Demo.ID);
assert.equal(normalized.characters.find(x=>x.id==='manual-created').character.name,'Kael Sparrow');
const bad=JSON.parse(JSON.stringify(details));bad.scores.STR=0;
assert.throws(()=>Import.createManual(bad),/STR score/);
assert.throws(()=>Import.createManual({...details,name:'  '}),/Character name/);
assert.throws(()=>Import.createManual({...details,level:21}),/Level/);
assert.throws(()=>Import.createManual({...details,saveProficiencies:['FAKE']}),/Unsupported/);
assert.throws(()=>Import.createManual({...details,skillProficiencies:['Teleportation']}),/Unsupported/);
assert.throws(()=>Import.createManual({...details,attack:{...details.attack,damage:'run(999)'}}),/Attack damage/);
assert.throws(()=>Import.createManual({...details,attack:{...details.attack,range:'magic'}}),/melee or ranged/);
const noAttack=Import.createManual({...details,attack:{name:'',bonus:0,damage:'',range:'melee'}});
assert.equal(noAttack.attacks.length,0);
assert.equal(Import.createManual({...details,level:1}).proficiency,2);
assert.equal(Import.createManual({...details,level:20}).proficiency,6);
assert.notStrictEqual(Import.createManual(details),Import.createManual(details));
console.log('PASS manual character factory, rules boundaries, vault isolation and invalid inputs');

const assert=require('node:assert/strict');
const A=require('../web/dnd-action.js');
const char=()=>({hp:{current:12,max:30,temp:2},resources:{Ki:{current:4,max:9},'Bardic Inspiration':{current:1,max:5}}});
const c=char(),heal={name:'Healing Light',activation:'action',resource:'Ki',cost:2,roll:'1d10+6',effect_kind:'heal'};
const plan=A.plan(c,heal);assert.deepEqual(plan.roll,{count:1,sides:10,modifier:6,expression:'1d10+6'});
assert.equal(c.resources.Ki.current,4,'planning may not mutate');
A.commit(c,plan);assert.equal(c.resources.Ki.current,2);assert.equal(A.applyHealing(c,16),16);assert.equal(c.hp.current,28);
assert.equal(A.applyHealing(c,40),2,'clamp to max');assert.equal(c.hp.temp,2,'healing never changes temp HP');
assert.throws(()=>A.plan(c,{...heal,cost:3}),/Not enough/);
assert.throws(()=>A.plan(c,{...heal,roll:'4d3'}),/Unsupported dice/);
assert.throws(()=>A.plan(c,{...heal,effect_kind:'damage'}),/Unsupported ability effect/);
assert.throws(()=>A.plan(c,{...heal,cost:-1}),/Invalid ability/);
assert.throws(()=>A.plan(c,{...heal,resource:'Unknown'}),/Resource not found/);
assert.throws(()=>A.plan(c,{...heal,roll:''}),/Healing requires/);
assert.throws(()=>A.plan(c,{...heal,damage:'not dice'}),/Unsupported dice/);
assert.equal(A.plan(c,{name:'Narrative',cost:0}).roll,null,'narrative action allowed');
assert.deepEqual(A.dice('d20-3'),{count:1,sides:20,modifier:-3,expression:'1d20-3'});
assert.throws(()=>A.dice('21d6'),/1–20/);
assert.throws(()=>A.dice('2d6+1d4'),/Unsupported dice/);
assert.throws(()=>A.applyHealing(c,-1),/Invalid healing/);
console.log('D&D action planning, validation, cost, manual healing, errors PASS');

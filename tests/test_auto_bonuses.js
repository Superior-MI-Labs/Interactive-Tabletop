'use strict';
const assert=require('node:assert/strict');
const A=require('../web/dnd-action.js');
const hero={effects:{active:[]}};
const guidance={id:'spell:guidance',name:'Guidance',target:'self',charges:1,bonus_dice:'1d4',concentration:true,auto_use:true};
hero.effects.active.push(guidance);
const get=(kind,reserved=[])=>A.compatibleBonuses(hero,kind,reserved);
assert.deepEqual(get('ability-check'),[{effectId:guidance.id,name:'Guidance',expression:'1d4',count:1,sides:4}]);
for(const kind of ['attack','save','concentration','damage','spell','untyped','target-save'])assert.equal(get(kind).length,0,kind);
assert.equal(get('ability-check',['spell:guidance']).length,0,'Another active throw reserves the one-use bonus.');
assert.equal(guidance.charges,1,'Selecting does not spend the charge.');
A.setAutoUse(hero,guidance.id,false);
assert.equal(get('ability-check').length,0);
assert.equal(guidance.charges,1,'Toggling off does not end the effect.');
A.setAutoUse(hero,guidance.id,true);
assert.equal(get('ability-check').length,1);
assert.equal(A.consumeCharge(hero,guidance.id).expression,'1d4');
assert.deepEqual(A.activeEffects(hero),[],'Final charge ends the effect and concentration.');
assert.equal(get('ability-check').length,0);
assert.throws(()=>A.setAutoUse(hero,'missing',true),/cannot automatically/);
hero.effects.active=[{...guidance,id:'legacy-guidance',charges:1,auto_use:undefined}];
assert.equal(get('ability-check').length,1,'Existing saves default to auto enabled.');
hero.effects.active[0].target='enemy';assert.equal(get('ability-check').length,0,'Self-only charged buff.');
hero.effects.active[0].target='self';hero.effects.active[0].bonus_scope='attack';assert.equal(get('ability-check').length,0,'Wrong roll scope.');
console.log('Effect-local auto use, compatibility, reservations, legacy default and charge lifecycle PASS');

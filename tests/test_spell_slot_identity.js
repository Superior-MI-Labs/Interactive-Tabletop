'use strict';
const assert=require('node:assert/strict');
const Slots=require('../web/dnd-slots.js');
const Engine=require('../web/dnd-action.js');
const Vault=require('../web/vault-store.js');
const Import=require('../web/character-import.js');
const legacy='First-level Spell Slots', modern='Level 1 Spell Slots';
const oldChar=()=>({schema_version:1,name:'Sky Blue Eyes',player:'P',species:'Tabaxi',hp:{current:13,max:20,temp:0},inventory:[],
 resources:{[legacy]:{current:2,max:2,reset:'long rest'},Ki:{current:19,max:19}},
 spells:[{id:'spell-15',name:'Cure Wounds',level:1,prepared:true,source:'Cleric'}],effects:{},actions:[],roll_history:[]});
assert.equal(Slots.levelFromName(legacy),1);
for(const name of ['Level 1 Spell Slots','1st-level Spell Slots','1st Level Spell Slots','Spell Slots Level 1','FIRST-level spell slots'])assert.equal(Slots.levelFromName(name),1,name);
assert.equal(Slots.levelFromName('Level 9 Spell Slots'),9);
for(const name of ['Ki','Pact Magic','Pact Spell Slots','Mystic Slots','Level 12 Spell Slots'])assert.equal(Slots.levelFromName(name),null,name);
const old=oldChar(),spell=old.spells[0];
assert.deepEqual(Engine.spellSlots(old).map(s=>[s.level,s.current,s.resource]),[[1,2,legacy]]);
const plan=Engine.planSpell(old,spell,1);
assert.equal(plan.resource,legacy,'Legacy plan must address actual resource key');
Engine.commitUsage(old,plan);
assert.equal(old.resources[legacy].current,1,'Only actual pool is spent');
const storage=Vault.migrateLegacy(old);
assert.deepEqual(Object.keys(storage.characters[0].character.resources).sort(),['Ki',modern]);
assert.equal(storage.characters[0].character.resources[modern].current,1);
const copied=Vault.normalize(storage);
assert.equal(copied.characters[0].character.resources[modern].current,1);
const duplicate=oldChar();duplicate.resources[modern]={current:1,max:2,reset:'long rest'};
assert.equal(Slots.poolFor(duplicate.resources,1).current,1,'Read-time duplicate pool must not inflate available slots');
const contradictory=oldChar();contradictory.resources[legacy].current=0;
contradictory.resources[modern]={current:2,max:2,reset:'long rest'};
assert.equal(Slots.poolFor(contradictory.resources,1).current,0,'Unmigrated aliases cannot hide spent slots');
assert.throws(()=>Engine.planSpell(contradictory,contradictory.spells[0],1),/remaining/);
const clean=Slots.normalize(duplicate.resources);
assert.deepEqual(Object.keys(clean).sort(),['Ki',modern]);
assert.equal(clean[modern].current,1,'A duplicate older label cannot magically restore slots');
assert.equal(Slots.normalize(clean)[modern].current,1,'Normalization must be idempotent');
assert.throws(()=>Slots.normalize({[legacy]:{current:5,max:2}}),/Invalid spell slot counts/);
const reimport=oldChar();delete reimport.resources[legacy];reimport.resources[modern]={current:2,max:2,reset:'long rest'};
const merged=Vault.reconcile(old,reimport);
assert.equal(merged.resources[modern].current,1,'Spend persists across old-name to new-name PDF reimport');
assert.equal(merged.resources[legacy],undefined,'Legacy alias is not a second pool');
assert.equal(merged.resources.Ki.current,19);
const upcast=oldChar();upcast.resources['Second-level Spell Slots']={current:1,max:1};
const p2=Engine.planSpell(upcast,upcast.spells[0],2);assert.equal(p2.resource,'Second-level Spell Slots');
Engine.commitUsage(upcast,p2);assert.equal(upcast.resources['Second-level Spell Slots'].current,0);
assert.equal(upcast.resources[legacy].current,2);
assert.throws(()=>Engine.planSpell(upcast,upcast.spells[0],2),/remaining/);
const cantrip={name:'Guidance',level:0,prepared:false};
assert.equal(Engine.planSpell(oldChar(),cantrip).cost,0);
const fields={CharacterName:'Importer QA','CLASS LEVEL':'Cleric 1',MaxHP:'9','spellSlotHeader1':'2 Slots OO','spellHeader1':'=== 1st LEVEL ===','spellName1':'Cure Wounds','spellPrepared1':'P'};
const fresh=Import.fromFields(fields);
assert.equal(fresh.resources[modern].current,2);assert.equal(fresh.spells[0].level,1);
assert.equal(Slots.normalize({PactMagic:{current:2,max:2}}).PactMagic.current,2);
console.log('Slot identity: legacy, duplicates, import, vault migration, reimport, upcast, cantrip PASS');

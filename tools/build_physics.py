"""Build an offline browser/Node script with the pinned Rapier WASM runtime.

Authored source: web/dice-physics.source.js and package-lock.json.
Output web/dice-physics.js is generated and untracked.
"""
from pathlib import Path
import shutil

ROOT=Path(__file__).resolve().parents[1]
WEB=ROOT/'web'
RAPIER=ROOT/'node_modules'/'@dimforge'/'rapier3d-compat'
js=RAPIER/'dist'/'rapier.cjs'
license_file=RAPIER/'LICENSE'
if not js.is_file() or not license_file.is_file():
    raise SystemExit('Physics dependency missing: run npm ci')
content="""/* GENERATED by tools/build_physics.py; do not edit. */
(function(root){
 const embedded={exports:{}};
 (function(module,exports){
"""+js.read_text(encoding='utf-8')+"""
 })(embedded,embedded.exports);
"""+(WEB/'dice-physics.source.js').read_text(encoding='utf-8')+"""
 root.DicePhysics=createDicePhysics(embedded.exports);
})(typeof globalThis !== 'undefined' ? globalThis : this);
if(typeof module === 'object' && module.exports)module.exports=globalThis.DicePhysics;
"""
(WEB/'dice-physics.js').write_text(content,encoding='utf-8')
(WEB/'vendor').mkdir(exist_ok=True)
shutil.copyfile(license_file, WEB/'vendor'/'rapier.LICENSE')
print('Prepared Rapier 0.21.0 physics runtime',len(content),'bytes')
